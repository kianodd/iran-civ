#!/usr/bin/env python3
"""Convert data/iran-provinces.geojson (GADM, WGS84) into js/paths.js:
simplified SVG path strings + label centroids, equirectangular projection
with cos(33 deg) longitude correction. Pure stdlib.
"""
import json, math, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEO = os.path.join(ROOT, 'data', 'iran-provinces.geojson')
OUT = os.path.join(ROOT, 'js', 'paths.js')

LON0, LAT0 = 44.0, 39.8          # top-left corner of the map
SX, SY = 43.6, 52.0              # px per degree (SX = SY * cos(33deg))
TOL = 0.02                       # Douglas-Peucker tolerance, degrees

# manual label offsets (dx, dy in px) for the small crowded provinces
LABEL_DXDY = {
    'tehran': (0, -14),
    'alborz': (-34, -6),
    'qom': (0, 16),
    'zanjan': (0, -10),
    'qazvin': (-6, -12),
}


def proj(lon, lat):
    return ((lon - LON0) * SX, (LAT0 - lat) * SY)


def _perp(p, a, b):
    ax, ay = a; bx, by = b; px, py = p
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return math.hypot(px - ax, py - ay)
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def dp(points, tol):
    """Douglas-Peucker on a list of (lon, lat)."""
    if len(points) <= 2:
        return points
    a, b = points[0], points[-1]
    dmax, idx = 0.0, -1
    for i in range(1, len(points) - 1):
        d = _perp(points[i], a, b)
        if d > dmax:
            dmax, idx = d, i
    if dmax > tol:
        return dp(points[:idx + 1], tol)[:-1] + dp(points[idx:], tol)
    return [a, b]


def ring_to_path(ring):
    pts = dp(ring, TOL)
    s = []
    for i, (lon, lat) in enumerate(pts):
        x, y = proj(lon, lat)
        s.append(('M' if i == 0 else 'L') + f'{x:.1f},{y:.1f}')
    return ''.join(s) + 'Z'


def main():
    d = json.load(open(GEO, encoding='utf-8'))
    paths, centroids = {}, {}
    for f in d['features']:
        pid = (f['properties'].get('id') or '').lower()
        pid = pid.replace('west-azarbaijan', 'west-azerbaijan')  # GADM spelling -> standard
        geom = f['geometry']
        polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
        # outer rings only (skip holes for the simplified render)
        parts = [ring_to_path(p[0]) for p in polys]
        paths[pid] = ''.join(parts)
        # centroid: vertex average of the largest polygon
        big = max(polys, key=lambda p: len(p[0]))
        xs, ys = [], []
        for lon, lat in big[0]:
            x, y = proj(lon, lat)
            xs.append(x); ys.append(y)
        cx, cy = sum(xs) / len(xs), sum(ys) / len(ys)
        dx, dy = LABEL_DXDY.get(pid, (0, 0))
        centroids[pid] = [round(cx + dx, 1), round(cy + dy, 1)]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('// Auto-generated by tools/build-paths.py from data/iran-provinces.geojson\n')
        fh.write('// Source: GADM 4.1 (gadm.org), enriched by power0matin/iran-provinces (CC BY).\n')
        fh.write('// Simplified (Douglas-Peucker 0.02 deg), equirectangular projection.\n')
        fh.write('const VIEWBOX = "0 0 860 790";\n')
        fh.write('const PATHS = ' + json.dumps(paths, ensure_ascii=False) + ';\n')
        fh.write('const CENTROIDS = ' + json.dumps(centroids, ensure_ascii=False) + ';\n')
    print(f'provinces: {len(paths)}  paths.js: {os.path.getsize(OUT)//1024} KB')


if __name__ == '__main__':
    main()
